
/* eslint-disable no-undef, @typescript-eslint/no-var-requires */

const fs = require('fs');
const path = require('path');
const process = require('process');

class Tasks {

    clean() {
        let opt = { recursive: true, force: true };
        fs.rmSync('bin', opt);
        fs.rmSync('tools/runtime/softfloatlib/obj', opt);
        fs.rmSync('tools/runtime/triwasmlib/obj', opt);
        fs.rmSync('tools/runtime/softfloatlib.wasm', opt);
        fs.rmSync('tools/runtime/triwasmlib.wasm', opt);
    }

    starters() {
        fs.mkdirSync('bin/js', { recursive: true });
        let skipStarters = new Set();
        for (let file of fs.readdirSync('tools/build/bin-include')) {
            fs.copyFileSync('tools/build/bin-include/' + file, 'bin/js/' + file);
            skipStarters.add(file);
        }
        for (let file of fs.readdirSync('bin/js')) {
            if (file.endsWith('.js') && !skipStarters.has(file)) {
                fs.copyFileSync('tools/build/starters/starter.bat', 'bin/' + file.replace('.js', '.bat'));
                fs.copyFileSync('tools/build/starters/starter.sh', 'bin/' + file.replace('.js', ''));
            }
        }
    }

    jsfixup() {
        fs.mkdirSync('bin/js', { recursive: true });
        for (let file of fs.readdirSync('bin/js')) {
            if (file.endsWith('.js')) {
                let text = fs.readFileSync('bin/js/' + file, 'utf-8');
                let replaced = text.replace(/ImPoRT/g, 'import');
                if (text != replaced) {
                    fs.writeFileSync('bin/js/' + file, replaced);
                }
            }
        }
    }

    copystatic() {
        for (let file of readdirSyncRecursive('build/static')) {
            if (fs.statSync('build/static/' + file).isFile()) {
                fs.mkdirSync(path.dirname('dist/' + file), { recursive: true });
                fs.copyFileSync('build/static/' + file, 'dist/' + file);
            } else {
                fs.mkdirSync('dist/' + file, { recursive: true });
            }
        }
    }

    copystartup() {
        for (let file of readdirSyncRecursive('runtime/startup')) {
            fs.copyFileSync('runtime/startup/' + file, 'dist/data/lib/' + file);
        }
    }

    licenses() {
        fs.mkdirSync('dist/bin', { recursive: true });
        fs.mkdirSync('dist/src', { recursive: true });
        fs.mkdirSync('dist/data/lib', { recursive: true });
        fs.mkdirSync('dist/data/gui', { recursive: true });
        fs.copyFileSync('COPYING.txt', 'dist/COPYING.txt');
        fs.copyFileSync('tools/COPYING.txt', 'dist/bin/COPYING.txt');
        fs.copyFileSync('trivm/COPYING.txt', 'dist/src/COPYING.txt');

        let libs = fs.readFileSync('runtime/COPYING.txt');
        libs += `
            ------------------------------------------------------------------------------------

            The "softfloatlib.wasm" library contains Berkeley SoftFloat library that is licensed
            under the following conditions.
            `.split('\n').map(x => x.trim()).join('\r\n');
        libs += fs.readFileSync('runtime/softfloatlib/Berkeley-SoftFloat/COPYING.txt');
        fs.writeFileSync('dist/data/lib/COPYING.txt', libs);
        fs.writeFileSync('dist/data/gui/COPYING.txt', 'TODO: Autogenerated: GPL + react + Blueprint.js + other dependencies');
    }
}

function readdirSyncRecursive(dir) {
    const files = fs.readdirSync(dir);
    const subdirs = files.filter(file => fs.statSync(dir + '/' + file).isDirectory());
    for (const subdir of subdirs) {
        let subfiles = readdirSyncRecursive(dir + '/' + subdir);
        subfiles = subfiles.map(file => subdir + '/' + file);
        files.splice(files.length, 0, ...subfiles);
    }
    return files;
}

process.chdir(`${__dirname}/../..`);
let tasks = new Tasks();
let allTasksNames = Object.getOwnPropertyNames(Tasks.prototype).filter(x => x !== 'constructor');
let list = (process.argv.length > 2) ? process.argv.slice(2) : allTasksNames;
for (let taskName of list) {
    console.log(`Running task: ${taskName}`);
    tasks[taskName]();
}
